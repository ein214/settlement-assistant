def seed(conn: sqlite3.Connection) -> None:
    # 원장은 append-only 트리거가 있어 DELETE 대신 테이블을 다시 만든다
    conn.executescript("""
        DROP TABLE IF EXISTS settlement_ledger;
        DROP TABLE IF EXISTS settlement_terms;
        DROP TABLE IF EXISTS contracts;
        DROP TABLE IF EXISTS providers;
        DROP TABLE IF EXISTS partners;
    """)
    init_db(conn)
    conn.executemany("INSERT INTO providers VALUES (?, ?, ?, ?)", PROVIDERS)
    conn.executemany(f"INSERT INTO contracts VALUES ({', '.join('?' * 14)})", CONTRACTS)
    conn.executemany(
        """INSERT INTO settlement_ledger
           (id, provider_id, contract_id, period, entry_type, amount, cancels_id, memo, recorded_at)
           VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)""",
        LEDGER,
    )
    conn.commit()


if __name__ == "__main__":
    with connect() as conn:
        seed(conn)
    print(f"Seeded dummy data into {DB_PATH}")
